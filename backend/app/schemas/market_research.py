"""Pydantic v2 schemas for Market and Competitor Research."""

from datetime import datetime
from typing import Dict, List, Optional
from pydantic import BaseModel, Field, HttpUrl


class SourceItem(BaseModel):
    """External source citation with verification metadata."""

    url: str = Field(..., description="Full source URL")
    title: str = Field(..., description="Document or website title")
    snippet: str = Field(default="", description="Relevant extracted excerpt or claim")
    retrieved_at: str = Field(..., description="ISO timestamp or date of retrieval")
    source_type: str = Field(default="website", description="website, official_company, industry_report, news")
    evidence_note: Optional[str] = Field(default=None, description="Observation regarding reliability or limitation")


class CompetitorProfile(BaseModel):
    """Structured competitor analysis."""

    name: str = Field(..., description="Competitor or product name")
    website: Optional[str] = Field(default=None, description="Official website or domain")
    product_summary: str = Field(..., description="Core product or service description")
    target_audience: str = Field(..., description="Primary audience targeted by competitor")
    pricing_model: str = Field(default="Subscription / Tiered", description="Freemium, Subscription, Usage-based, Enterprise")
    estimated_pricing: str = Field(default="Unknown / Custom Quote", description="Observed pricing or plan tiers")
    key_features: List[str] = Field(default_factory=list, description="Main product capabilities")
    positioning: str = Field(..., description="Market positioning and brand claim")
    differentiators: List[str] = Field(default_factory=list, description="Claimed competitive advantages")
    strengths: List[str] = Field(default_factory=list, description="Key strengths observed")
    weaknesses: List[str] = Field(default_factory=list, description="Known complaints, gaps, or weaknesses")
    source_urls: List[str] = Field(default_factory=list, description="Supporting source URLs")


class MarketTrendItem(BaseModel):
    """Macro or micro industry trend."""

    trend_title: str = Field(..., description="Name of market trend")
    description: str = Field(..., description="Detailed trend description and drivers")
    implications_for_founder: str = Field(..., description="How this impacts strategic choices")
    supporting_sources: List[str] = Field(default_factory=list, description="Citations supporting this trend")


class ComparisonCriterionRow(BaseModel):
    """Row in feature/attribute comparison matrix."""

    criterion: str = Field(..., description="Comparison dimension (e.g. Pricing, Real-time sync, Self-serve)")
    founder_solution: str = Field(..., description="How the user's business approaches this dimension")
    competitor_comparison: Dict[str, str] = Field(
        default_factory=dict,
        description="Map of competitor_name -> rating or explanation",
    )


class MarketSizingAnalysis(BaseModel):
    """Sizing breakdown with strict disclaimer against hallucinated certainty."""

    market_definition: str = Field(..., description="Boundary of addressable domain")
    tam_description: str = Field(..., description="Total Addressable Market qualitative scope")
    sam_description: str = Field(..., description="Serviceable Addressable Market scope")
    som_description: str = Field(..., description="Serviceable Obtainable Market initial target")
    sizing_caveats: str = Field(
        default="Market size figures are qualitative planning estimates and should be backed by field surveys prior to institutional financing.",
        description="Mandatory methodological disclaimer",
    )


class MarketResearchReportData(BaseModel):
    """Complete structured output for Market and Competitor Research."""

    executive_summary: str = Field(..., description="Overview of competitive landscape and market conditions")
    industry_definition: str = Field(..., description="Industry sector and market segment")
    market_trends: List[MarketTrendItem] = Field(..., min_length=2)
    barriers_to_entry: List[str] = Field(..., min_length=2)
    distribution_channels: List[str] = Field(..., min_length=2)
    competitors: List[CompetitorProfile] = Field(..., min_length=2)
    comparison_matrix: List[ComparisonCriterionRow] = Field(..., min_length=3)
    market_sizing: MarketSizingAnalysis
    sources: List[SourceItem] = Field(default_factory=list, description="List of all referenced external sources")
    research_methodology_disclaimer: str = Field(
        default="This research was generated by synthesizing live external search results and AI-assisted competitor extraction. All competitor claims and pricing should be verified on vendor websites.",
        description="Disclaimer",
    )


class MarketResearchUpdateRequest(BaseModel):
    """Payload for updating or manually refining research report content."""

    content: MarketResearchReportData
